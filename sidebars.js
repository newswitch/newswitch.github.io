import {domains} from './src/data/domains.mjs';

/** Top-level domains share homepage metadata; all descendants mirror docs/. */
const sidebars = {
  docsSidebar: [
    'intro',
    ...domains.map(domain => ({
      type:'category',
      label:domain.title,
      className:'sidebar-domain sidebar-domain--' + domain.sidebarIcon,
      collapsed:true,
      link:{type:'doc', id:domain.docId},
      items:[{type:'autogenerated', dirName:domain.directory}],
    })),
  ],
};

export default sidebars;
